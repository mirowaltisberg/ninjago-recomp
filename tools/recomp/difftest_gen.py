"""Generate the instruction-level differential test cases (tests/difftest).

    python -m recomp.difftest_gen <so> --out build/difftest --per-shape 4 [--base 0x100000]

Picks up to N real instances of every instruction shape (capstone id, condition, S flag, writeback, operand
kinds and shift kinds) among the non-branch instructions of the discovered ARM functions, lifts each one and
writes cases.c / cases.h for the C rig, which runs every case under Unicorn and as lifted C and compares.
Exclusives are excluded (an isolated strex always fails without a monitor; Task 20 tests them with threads).
"""
import argparse
import collections
import os

import capstone
from capstone import arm

from .discover import discover
from .elfimage import GuestElf
from .lift import LiftCtx, REG_NUM, Unsupported, lift_insn

BRANCHES = {arm.ARM_INS_B, arm.ARM_INS_BL, arm.ARM_INS_BLX, arm.ARM_INS_BX, arm.ARM_INS_BXJ}
EXCLUDED = BRANCHES | {arm.ARM_INS_LDREX, arm.ARM_INS_LDREXB, arm.ARM_INS_LDREXH, arm.ARM_INS_LDREXD,
                       arm.ARM_INS_STREX, arm.ARM_INS_STREXB, arm.ARM_INS_STREXH, arm.ARM_INS_STREXD,
                       arm.ARM_INS_CLREX, arm.ARM_INS_SVC, arm.ARM_INS_BKPT, arm.ARM_INS_UDF}
BASE_IN_OP0 = {arm.ARM_INS_LDM, arm.ARM_INS_LDMDA, arm.ARM_INS_LDMDB, arm.ARM_INS_LDMIB, arm.ARM_INS_STM,
               arm.ARM_INS_STMDA, arm.ARM_INS_STMDB, arm.ARM_INS_STMIB, arm.ARM_INS_VLDMIA, arm.ARM_INS_VLDMDB,
               arm.ARM_INS_VSTMIA, arm.ARM_INS_VSTMDB}


def shape(ci):
    kinds = []
    for op in ci.operands:
        if op.type == arm.ARM_OP_REG:
            kinds.append(("r", op.shift.type))
        elif op.type == arm.ARM_OP_MEM:
            kinds.append(("m", op.mem.index != 0, bool(op.subtracted), op.shift.type, op.mem.base == arm.ARM_REG_PC))
        else:
            kinds.append(op.type)
    return ci.id, ci.cc, ci.update_flags, ci.writeback, tuple(kinds)


def address_regs(ci):
    """(base register numbers, index register numbers) the rig must point into scratch memory / keep small."""
    bases, idx = set(), set()
    for op in ci.operands:
        if op.type == arm.ARM_OP_MEM:
            if op.mem.base and op.mem.base != arm.ARM_REG_PC:
                bases.add(REG_NUM[ci.reg_name(op.mem.base)])
            if op.mem.index:
                idx.add(REG_NUM[ci.reg_name(op.mem.index)])
    if ci.id in BASE_IN_OP0 and ci.operands and ci.operands[0].type == arm.ARM_OP_REG:
        bases.add(REG_NUM[ci.reg_name(ci.operands[0].reg)])
    return bases, idx


def collect(so, base, per_shape):
    elf = GuestElf.load(so, base)
    prog = discover(elf)
    md = capstone.Cs(capstone.CS_ARCH_ARM, capstone.CS_MODE_ARM)
    md.detail = True
    by_shape = collections.defaultdict(list)
    freq = collections.Counter()
    for f in prog.functions.values():
        for a in sorted(f.insns):
            ci = next(md.disasm(elf.read_bytes(a, 4), a), None)
            if ci is None or ci.id in EXCLUDED or arm.ARM_REG_PC in ci.regs_access()[1]:
                continue
            freq[ci.mnemonic] += 1
            by_shape[shape(ci)].append(ci)
    lc = LiftCtx(base=base, plt=elf.plt)
    cases, unsupported = [], collections.Counter()
    for key in sorted(by_shape, key=lambda k: (k[0], k[1], k[2], k[3], repr(k[4]))):
        group = sorted(by_shape[key], key=lambda ci: ci.address)
        step = max(1, len(group) // per_shape)
        for ci in group[::step][:per_shape]:
            try:
                body = lift_insn(ci, lc)
            except Unsupported:
                unsupported[ci.mnemonic] += 1
                break  # one failing instance is enough to count the shape as unsupported
            bases, idx = address_regs(ci)
            if bases & idx:
                continue  # a register used as both base and index cannot be both a pointer and small
            cases.append((ci, body, bases, idx))
    return cases, unsupported, freq, len(by_shape)


def write(out, cases):
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "cases.h"), "w") as h:
        h.write("/* Generated by tools/recomp/difftest_gen.py. */\n#include <stdint.h>\n\n#include \"nj/guest.h\"\n\n"
                "typedef struct {\n    uint32_t addr, word;\n    void (*fn)(NjCtx *);\n"
                "    uint16_t mem_regs, idx_regs;\n    const char *text;\n} NjCase;\n"
                "extern const NjCase nj_cases[];\nextern const unsigned nj_case_count;\n")
    with open(os.path.join(out, "cases.c"), "w") as c:
        c.write("/* Generated by tools/recomp/difftest_gen.py. */\n#include \"cases.h\"\n#include \"recomp_rt.h\"\n\n")
        for i, (ci, body, _, _) in enumerate(cases):
            c.write(f"/* {ci.address:#x}: {ci.mnemonic} {ci.op_str} */\nstatic void t_{i}(NjCtx *c) {{\n")
            c.write("".join(f"    {line}\n" for line in body))
            c.write("}\n")
        c.write("\nconst NjCase nj_cases[] = {\n")
        for i, (ci, _, bases, idx) in enumerate(cases):
            mask = sum(1 << r for r in bases)
            imask = sum(1 << r for r in idx)
            text = f"{ci.mnemonic} {ci.op_str}".replace("\\", "\\\\").replace('"', '\\"')
            word = int.from_bytes(ci.bytes, "little")
            c.write(f"    {{0x{ci.address:08x}u, 0x{word:08x}u, t_{i}, 0x{mask:04x}, 0x{imask:04x}, \"{text}\"}},\n")
        if not cases:
            c.write("    {0, 0, 0, 0, 0, 0},\n")
        c.write(f"}};\nconst unsigned nj_case_count = {len(cases)};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("so")
    ap.add_argument("--out", required=True)
    ap.add_argument("--per-shape", type=int, default=4)
    ap.add_argument("--base", type=lambda s: int(s, 0), default=0x100000)
    args = ap.parse_args()
    if not os.path.exists(args.so):
        write(args.out, [])
        print("difftest_gen: guest library not present, no cases")
        return
    cases, unsupported, freq, nshapes = collect(args.so, args.base, args.per_shape)
    write(args.out, cases)
    print(f"difftest_gen: {nshapes} shapes, {len(cases)} cases")
    if unsupported:
        print(f"Unsupported: {sum(unsupported.values())} shapes, {len(unsupported)} mnemonics "
              "(mnemonic, uses in the library, shapes):")
        for m, n in sorted(unsupported.items(), key=lambda kv: -freq[kv[0]]):
            print(f"  {m:12s} {freq[m]:7d} {n:5d}")


if __name__ == "__main__":
    main()
